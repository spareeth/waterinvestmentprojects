/** Lower-case, accents removed, so "cote" finds "Côte d'Ivoire" and "turkiye" finds "Türkiye". */
export function normaliseCountryText(text: string): string {
  return text
    .normalize("NFD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9 ]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function matchRank(query: string, country: WorldCountry): number | null {
  if (country.iso3.toLowerCase() === query) return 0;
  const names = [country.name, ...(ALSO_KNOWN_AS[country.iso3] ?? [])].map(
    normaliseCountryText,
  );
  if (names.some((n) => n.startsWith(query))) return 1;
  if (names.some((n) => n.split(" ").some((w) => w.startsWith(query))))
    return 2;
  if (names.some((n) => n.includes(query))) return 3;
  return null;
}

/**
 * Countries whose name (or a common other name, or the ISO code) matches what was typed: names starting with the
 * text first, then names with a word starting with it, then names containing it. Empty text matches nothing.
 */
export function searchWorldCountries(text: string, limit = 8): WorldCountry[] {
  const query = normaliseCountryText(text);
  if (!query) return [];
  return WORLD_COUNTRIES.map((country) => ({
    country,
    rank: matchRank(query, country),
  }))
    .filter(
      (m): m is { country: WorldCountry; rank: number } => m.rank !== null,
    )
    .sort(
      (a, b) =>
        a.rank - b.rank || a.country.name.localeCompare(b.country.name, "en"),
    )
    .slice(0, limit)
    .map((m) => m.country);
}
